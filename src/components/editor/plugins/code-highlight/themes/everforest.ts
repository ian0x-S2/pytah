/**
 * Everforest for twinkleplop (local theme, not an upstream package).
 *
 * Token colors are copied verbatim from the official sainnhe/everforest
 * VS Code theme (`everforest-dark` / `everforest-light` tokenColors):
 * keyword red, operators orange, strings/attrs yellow, functions green,
 * imports aqua, types blue, constants purple, plain text fg, comments
 * gray italic. Grouping follows the reference (one hex per hue family);
 * keys with no direct TextMate scope use the closest analog (tag names
 * follow the green JSX rule, HTML tags the orange `entity.name.tag`
 * rule, lifetimes orange, variants blue like semantic enumMembers).
 *
 * Fidelity is intentional: the reference itself sits below WCAG AA on
 * several tokens (dark gray markers 3.8; light yellow strings 1.9 on a
 * bright bg), so this family is exempt from the repo's AAA/AA contrast
 * test — see `registry.test.ts`. Dark bg `#2d353b`, light bg `#fdf6e3`.
 *
 * Role assignment toward the VS Code reference rendering (plain
 * `import`/`export`/`function`, PascalCase values as types, orange JSX
 * brackets, plain JSX props) lives in `token-roles.ts` — the palette
 * below stays a verbatim copy of the Shiki reference.
 */

